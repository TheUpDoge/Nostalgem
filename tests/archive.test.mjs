import { test } from "node:test";
import assert from "node:assert/strict";
import { parseLength, cleanTitle, tidyEpisode, fileTitle, fileYear, contentYear, pickPrograms, buildChannel, compileExclude, subtitleLang, searchUrl, downloadUrl, corsUrl, sameShowKey } from "../web/js/archive.js";

test("runtime strings in every shape the Archive uses", () => {
  assert.equal(parseLength("5971.27"), 5971.27);
  assert.equal(parseLength("99:31"), 5971);
  assert.equal(parseLength("1:39:30"), 5970);
  assert.equal(parseLength("74 min"), 4440);
  assert.equal(parseLength("105 min."), 6300);
  assert.equal(parseLength("1 hr 20 min"), 4800);
  assert.equal(parseLength(""), 0);
  assert.equal(parseLength("unknown"), 0);
});

test("titles lose uploader decorations", () => {
  assert.equal(cleanTitle("Gunsmoke - Single Episodes"), "Gunsmoke");
  assert.equal(cleanTitle("OTRR Frontier Gentleman Singles"), "Frontier Gentleman");
  assert.equal(cleanTitle("Our Miss Brooks 178 Eps + 2 Auditions"), "Our Miss Brooks");
  assert.equal(cleanTitle("The Roy Rogers Show PD Episodes"), "The Roy Rogers Show");
  assert.equal(cleanTitle("''The Lone Ranger'' - The Legion of Old Timers"), "The Lone Ranger - The Legion of Old Timers");
  assert.equal(cleanTitle("Angel and the Badman"), "Angel and the Badman");
});

test("episode titles drop the show name, dates and numbers", () => {
  assert.equal(tidyEpisode("Frontier Gentleman 1958-07-06 (022) The Education of Kid Yancey", "Frontier Gentleman"), "The Education of Kid Yancey");
  assert.equal(tidyEpisode("Gunsmoke 52-04-26 (001) Billy the Kid", "Gunsmoke"), "Billy the Kid");
  assert.equal(tidyEpisode("05281974 the defenders", "Future Tense"), "the defenders");
  assert.equal(tidyEpisode("Hard Luck Story", "The Roy Rogers Show"), "Hard Luck Story");
  assert.equal(fileTitle("Dimension_X_1951-07-26__41_Courtesy.mp3"), "Dimension X 1951-07-26 41 Courtesy");
  assert.equal(fileTitle("05281974-the-defenders.mp3"), "05281974-the-defenders");
  assert.equal(fileTitle("the-defenders_512kb.mp4"), "the defenders");
});

test("subtitle languages from file names", () => {
  assert.equal(subtitleLang("Sintel_es.srt"), "es");
  assert.equal(subtitleLang("Movie.Spanish.srt"), "es");
  assert.equal(subtitleLang("film.en.vtt"), "en");
  assert.equal(subtitleLang("subtitles_DE.srt"), "de");
  assert.equal(subtitleLang("film.srt"), "");
});

test("whole-word exclusions", () => {
  const re = compileExclude(["sex", "amos 'n' andy", "rarbg"]);
  assert.ok(re.test("Sex Madness"));
  assert.ok(re.test("The Amos 'n' Andy Show"));
  assert.ok(re.test("Movie.1950.RARBG.mp4"));
  assert.ok(!re.test("Sussex Downs"));
  assert.ok(!re.test("Essex County"));
  assert.equal(compileExclude([]), null);
});

const feature = {
  metadata: { identifier: "angel_and_the_badman", title: "Angel and the Badman", date: "1947", description: "<p>John Wayne plays Quirt Evans.</p>", runtime: "1:39:30" },
  files: [
    { name: "angel_and_the_badman.mpeg", format: "MPEG2", source: "original", length: "5971.1" },
    { name: "angel_and_the_badman.mp4", format: "h.264", source: "derivative", original: "angel_and_the_badman.mpeg", length: "5971.27" },
    { name: "angel_and_the_badman_512kb.mp4", format: "512Kb MPEG4", source: "derivative", original: "angel_and_the_badman.mpeg", length: "5971" },
    { name: "angel_and_the_badman.mp3", format: "MP3", source: "derivative", original: "angel_and_the_badman.mpeg", length: "99:31" },
    { name: "angel_and_the_badman.asr.srt", format: "SubRip", source: "original" },
    { name: "angel_and_the_badman.autogenerated.vtt", format: "Web Video Text Tracks", source: "original" },
    { name: "angel_and_the_badman.es.srt", format: "SubRip", source: "original" },
  ],
};

test("a feature film: the best MP4, its length, year and subtitles", () => {
  const [p, ...rest] = pickPrograms(feature, { kind: "video" });
  assert.equal(rest.length, 0, "the 512kb copy is the same film, not another program");
  assert.equal(p.f, "angel_and_the_badman.mp4");
  assert.equal(p.d, 5971);
  assert.equal(p.y, 1947);
  assert.equal(p.t, "Angel and the Badman");
  assert.equal(p.e, undefined);
  // human-made Spanish first, the auto captions last, the old .asr.srt noise not at all
  assert.deepEqual(p.cc, [
    ["angel_and_the_badman.es.srt", "es"],
    ["angel_and_the_badman.autogenerated.vtt", "", 1],
  ]);
});

test("length limits keep a feature off a channel of shorts", () => {
  assert.equal(pickPrograms(feature, { kind: "video", maxS: 30 * 60 }).length, 0);
});

