import { test } from "node:test";
import assert from "node:assert/strict";
import { srtToVtt, pickSubtitle, subtitleLabel } from "../web/js/captions.js";

test("SubRip becomes WebVTT", () => {
  const srt = "﻿1\r\n00:00:07,250 --> 00:00:08,220\r\nWell, howdy.\r\n\r\n2\r\n00:00:15,23 --> 00:00:17,09\r\n{\\an8}Mighty <i>fine</i> day.\r\n";
  const vtt = srtToVtt(srt);
  assert.match(vtt, /^WEBVTT\n/);
  assert.match(vtt, /00:00:07\.250 --> 00:00:08\.220\nWell, howdy\./);
  // two-digit fractions are hundredths: ,23 is 230 ms
  assert.match(vtt, /00:00:15\.230 --> 00:00:17\.090\nMighty <i>fine<\/i> day\./);
  assert.doesNotMatch(vtt, /\\an8/);
});

test("single-digit hours are padded and cue numbers dropped", () => {
  const vtt = srtToVtt("12\n0:01:02,5 --> 0:01:04,000\nHi");
  assert.match(vtt, /00:01:02\.500 --> 00:01:04\.000\nHi/);
  assert.doesNotMatch(vtt, /^12$/m);
});

test("WebVTT passes through", () => {
  const v = "WEBVTT\n\n00:00.000 --> 00:02.000\nHey";
  assert.equal(srtToVtt(v).trim(), v);
});

test("subtitle choice: wanted language, then English, then auto captions", () => {
  const cc = [
    ["film.es.srt", "es"],
    ["film.en.srt", "en"],
    ["film.autogenerated.vtt", "", 1],
  ];
  assert.equal(pickSubtitle(cc, "es")[0], "film.es.srt");
  assert.equal(pickSubtitle(cc, "fr")[0], "film.en.srt");
  assert.equal(pickSubtitle(cc, "any")[0], "film.en.srt");
  assert.equal(pickSubtitle([["film.autogenerated.vtt", "", 1]], "en")[0], "film.autogenerated.vtt");
  assert.equal(subtitleLabel(cc[2]), "CC (auto)");
  assert.equal(subtitleLabel(cc[0]), "Español");
});

test("strict mode: Spanish or nothing", () => {
  assert.equal(pickSubtitle([["film.en.srt", "en"]], "es", true), null);
  assert.equal(pickSubtitle([["film.spa.srt", "es"]], "es", true)[0], "film.spa.srt");
  assert.equal(pickSubtitle([], "es"), null);
});
