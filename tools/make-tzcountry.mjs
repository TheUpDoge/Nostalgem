#!/usr/bin/env node
// Writes web/js/tzcountry.js from the system's time zone database (tzdata): which country each time
// zone (and its old alias) is in, and the list of country codes. The TV uses it to tell which country
// it's in from its time zone, so YouTube programs blocked there can be left out of the schedule.
//
//   node tools/make-tzcountry.mjs [/usr/share/zoneinfo]

import { readFile, writeFile } from "node:fs/promises";

const dir = (process.argv[2] || "/usr/share/zoneinfo").replace(/\/$/, "");
const zoneTab = await readFile(dir + "/zone.tab", "utf8");
const zi = await readFile(dir + "/tzdata.zi", "utf8");
const iso = await readFile(dir + "/iso3166.tab", "utf8");

const zoneCc = {};
for (const line of zoneTab.split("\n")) {
  if (!line || line[0] === "#") continue;
  const [cc, , tz] = line.split("\t");
  if (cc && tz) zoneCc[tz] = cc;
}
// "L Target Alias" lines: old names browsers still report (Asia/Calcutta, America/Buenos_Aires, US/Eastern).
for (const line of zi.split("\n")) {
  const m = /^L (\S+) (\S+)$/.exec(line);
  if (m && zoneCc[m[1]] && !zoneCc[m[2]]) zoneCc[m[2]] = zoneCc[m[1]];
}
const byCc = {};
Object.keys(zoneCc)
  .sort()
  .forEach((tz) => (byCc[zoneCc[tz]] = byCc[zoneCc[tz]] || []).push(tz));
const countries = iso
  .split("\n")
  .filter((l) => l && l[0] !== "#")
  .map((l) => l.split("\t")[0])
  .filter((cc) => /^[A-Z]{2}$/.test(cc))
  .sort();
const packed = Object.keys(byCc)
  .sort()
  .map((cc) => cc + ":" + byCc[cc].join(","))
  .join(";");
const out =
  "// Generated by tools/make-tzcountry.mjs from tzdata. Don't edit by hand.\n" +
  "// Which country each time zone is in (\"CC:Zone,Zone;CC:…\"), and every ISO 3166 country code.\n" +
  "export const TZ_COUNTRY = " +
  JSON.stringify(packed) +
  ";\n" +
  "export const COUNTRIES = " +
  JSON.stringify(countries.join("")) +
  ";\n";
await writeFile(new URL("../web/js/tzcountry.js", import.meta.url), out);
console.log("web/js/tzcountry.js: " + Object.keys(zoneCc).length + " time zones in " + Object.keys(byCc).length + " countries, " + countries.length + " country codes, " + out.length + " bytes");
